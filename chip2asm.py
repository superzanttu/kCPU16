#!/usr/bin/env python3
"""Convert a CHIP-8 binary module (.ch8) into an include-friendly kCPU16 .asm module."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path


def parse_int(value: str) -> int:
    """Parse an integer in decimal or 0x/0o/0b notation."""
    return int(value, 0)


def sanitize_module_name(name: str) -> str:
    """Create a safe label suffix for assembler symbols."""
    cleaned = re.sub(r"[^A-Za-z0-9_]", "_", name.strip())
    cleaned = re.sub(r"_+", "_", cleaned).strip("_")
    if not cleaned:
        cleaned = "module"
    if cleaned[0].isdigit():
        cleaned = f"m_{cleaned}"
    return cleaned.lower()


def format_db_rows(data: bytes, bytes_per_line: int) -> list[str]:
    rows: list[str] = []
    for index in range(0, len(data), bytes_per_line):
        chunk = data[index : index + bytes_per_line]
        row = ", ".join(f"0x{byte:02X}" for byte in chunk)
        rows.append(f"        .db {row}")
    return rows


def format_word(value: int) -> str:
    if value < 0 or value > 0xFFFF:
        raise ValueError(f"value out of 16-bit range: {value}")
    return f"0x{value:04X}"


def compute_module_end_addr_word(load_addr: int, data_size: int) -> int:
    """
    Return module end address as 16-bit word.

    For empty modules this returns the last address before load_addr in modulo
    16-bit space, i.e. (load_addr - 1) & 0xFFFF.
    """
    if data_size < 0:
        raise ValueError("data size must be >= 0")
    if data_size == 0:
        return (load_addr - 1) & 0xFFFF
    end_addr = load_addr + data_size - 1
    if end_addr > 0xFFFF:
        raise ValueError(
            "module does not fit in 16-bit address space with given load address"
        )
    return end_addr


def build_output(
    *,
    source_path: Path,
    module_name: str,
    load_addr: int,
    data: bytes,
    bytes_per_line: int,
) -> str:
    prefix = f"chip8_mod_{sanitize_module_name(module_name)}"
    end_addr_word = compute_module_end_addr_word(load_addr, len(data))
    source_name = source_path.name.replace("\\", "\\\\").replace('"', '\\"')

    lines: list[str] = [
        "; Auto-generated by chip2asm.py",
        "; Include-friendly CHIP-8 module data for kCPU16",
        ";",
        f"; Source: {source_name}",
        f"; Module symbol prefix: {prefix}",
        ";",
        "; Exported symbols:",
        f";   {prefix}_source_name",
        f";   {prefix}_load_addr",
        f";   {prefix}_entry_addr",
        f";   {prefix}_size",
        f";   {prefix}_end_addr",
        f";   {prefix}_data",
        f";   {prefix}_data_end",
        "",
        f"{prefix}_source_name:",
        f'        .dstr "{source_name}"',
        f"{prefix}_load_addr:",
        f"        .dw {format_word(load_addr)}",
        f"{prefix}_entry_addr:",
        f"        .dw {format_word(load_addr)}",
        f"{prefix}_size:",
        f"        .dw {format_word(len(data))}",
        f"{prefix}_end_addr:",
        f"        .dw {format_word(end_addr_word)}",
        f"{prefix}_data:",
    ]

    if data:
        lines.extend(format_db_rows(data, bytes_per_line))
    else:
        lines.append("        ; Empty module")

    lines.extend([f"{prefix}_data_end:", ""])
    return "\n".join(lines)


def convert_file(
    *,
    input_path: Path,
    output_path: Path,
    module_name: str,
    load_addr: int,
    bytes_per_line: int,
) -> None:
    if load_addr < 0 or load_addr > 0xFFFF:
        raise ValueError("load address must be in range 0..0xFFFF")
    if bytes_per_line < 1:
        raise ValueError("bytes-per-line must be >= 1")

    data = input_path.read_bytes()
    if len(data) > 0xFFFF:
        raise ValueError("module size must be in range 0..0xFFFF bytes")
    compute_module_end_addr_word(load_addr, len(data))
    output_text = build_output(
        source_path=input_path,
        module_name=module_name,
        load_addr=load_addr,
        data=data,
        bytes_per_line=bytes_per_line,
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(output_text, encoding="utf-8")


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Convert CHIP-8 .ch8 binary into a kCPU16 .asm include module "
            "containing ROM bytes and module metadata."
        )
    )
    parser.add_argument(
        "input",
        type=Path,
        help="Input CHIP-8 binary (.ch8)",
    )
    parser.add_argument(
        "output",
        nargs="?",
        type=Path,
        help="Output .asm file (default: <input-stem>.asm in same directory)",
    )
    parser.add_argument(
        "--module-name",
        help="Module name used in symbol prefix (default: input file stem)",
    )
    parser.add_argument(
        "--load-addr",
        type=parse_int,
        default=0x200,
        help="CHIP-8 load/entry address metadata (default: 0x200)",
    )
    parser.add_argument(
        "--bytes-per-line",
        type=int,
        default=16,
        help="How many .db bytes to emit per line (default: 16)",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(sys.argv[1:] if argv is None else argv)
    input_path: Path = args.input
    output_path: Path = args.output or input_path.with_suffix(".asm")

    if not input_path.exists():
        print(f"Error: input file does not exist: {input_path}", file=sys.stderr)
        return 1
    if not input_path.is_file():
        print(f"Error: input path is not a file: {input_path}", file=sys.stderr)
        return 1

    module_name = args.module_name or input_path.stem

    try:
        convert_file(
            input_path=input_path,
            output_path=output_path,
            module_name=module_name,
            load_addr=args.load_addr,
            bytes_per_line=args.bytes_per_line,
        )
    except ValueError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1
    except OSError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1

    print(f"Wrote {output_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
