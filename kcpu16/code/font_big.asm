; =============================================================================
; font_big.asm — BIG-fonttidata
; =============================================================================
;
; Kuvaa BIG-nimisen pikseleistä koostuvan näyttöfontin.
; Jokainen merkki on 6×8 pikselimatriisi:
;   - oikeanpuoleisin sarake (sarake 5) on aina tyhjä
;   - alin rivi (rivi 7) on aina tyhjä
;   => tehollinen pikseliala 5×7 (sarakkeet 0–4, rivit 0–6)
;
; FORMAATTI — 4 sanaa per merkki, 2 riviä pakattuna per sana:
;
;   Sana 0:  bitit 15–10 = rivi 0  |  bitit 9–4 = rivi 1  |  bitit 3–0 = 0000
;   Sana 1:  bitit 15–10 = rivi 2  |  bitit 9–4 = rivi 3  |  bitit 3–0 = 0000
;   Sana 2:  bitit 15–10 = rivi 4  |  bitit 9–4 = rivi 5  |  bitit 3–0 = 0000
;   Sana 3:  bitit 15–10 = rivi 6  |  bitit 9–4 = rivi 7  |  bitit 3–0 = 0000
;             (rivi 7 on aina 0 — alin rivi tyhjä)
;
; RIVISANA (6 bittiä):
;   bitti 5 = sarake 0 (vasen)      1 = pikseli päällä
;   bitti 4 = sarake 1              0 = pikseli pois
;   bitti 3 = sarake 2
;   bitti 2 = sarake 3
;   bitti 1 = sarake 4
;   bitti 0 = sarake 5 (oikea) — aina 0
;
; MERKKIJÄRJESTYS (indeksit 0–12):
;   0–9  = numerot '0'–'9'
;   10   = ':' (kaksoispiste)
;   11   = '.' (piste)
;   12   = ' ' (välilyönti)
;
; KÄYTTÖ PIIRTOKOODISSA:
;   osoite     = BIG_FONT + merkki_indeksi * BIG_WORDS_PER_CHAR
;   For sana_i in 0..3:
;     sana     = MEM[osoite + sana_i]
;     ylärivi  = (sana >> BIG_ROW_SHIFT) & BIG_ROW_MASK    ; rivit 0,2,4,6
;     alarivi  = (sana >> 4)             & BIG_ROW_MASK    ; rivit 1,3,5,7
;   Piirtorivi: bitti b (5..1) asettuna → piirrä pikseli sarakkeelle (5−b)
;
; PIKSELIKOMMENTIT:
;   Kuusi merkkiä sarake 0..5: X=pikseli päällä, .=pois
;   Esim. ".XXX.." tarkoittaa sarak. 0=. 1=X 2=X 3=X 4=. 5=. (aina tyhjä)
;
; =============================================================================

.const BIG_CHAR_W,        6  ; pikseleitä per merkki vaakasuunnassa
.const BIG_CHAR_H,        8  ; pikseleitä per merkki pystysuunnassa
.const BIG_WORDS_PER_CHAR, 4  ; muistisanoja per merkki
.const BIG_ROW_SHIFT,    10  ; bittisiirros ylärividataan (bitit 15–10)
.const BIG_ROW_MASK,   0x3F  ; 6-bittinen maski rivipikseleihin

BIG_FONT:

    ; -----------------------------------------------------------------------
    ; Merkki 0: '0'       sarake: 012345
    ;                   0: .XXX..
    ;                   1: X...X.
    ;                   2: X...X.
    ;                   3: X...X.
    ;                   4: X...X.
    ;                   5: X...X.
    ;                   6: .XXX..
    ;                   7: ......  (aina tyhjä)
    ; -----------------------------------------------------------------------
    .db 0b0111001000100000   ; r0:.XXX.. r1:X...X.
    .db 0b1000101000100000   ; r2:X...X. r3:X...X.
    .db 0b1000101000100000   ; r4:X...X. r5:X...X.
    .db 0b0111000000000000   ; r6:.XXX.. r7:......

    ; -----------------------------------------------------------------------
    ; Merkki 1: '1'       sarake: 012345
    ;                   0: ..X...
    ;                   1: .XX...
    ;                   2: ..X...
    ;                   3: ..X...
    ;                   4: ..X...
    ;                   5: ..X...
    ;                   6: .XXX..
    ;                   7: ......
    ; -----------------------------------------------------------------------
    .db 0b0010000110000000   ; r0:..X... r1:.XX...
    .db 0b0010000010000000   ; r2:..X... r3:..X...
    .db 0b0010000010000000   ; r4:..X... r5:..X...
    .db 0b0111000000000000   ; r6:.XXX.. r7:......

    ; -----------------------------------------------------------------------
    ; Merkki 2: '2'       sarake: 012345
    ;                   0: .XXX..
    ;                   1: X...X.
    ;                   2: ....X.
    ;                   3: ...X..
    ;                   4: ..X...
    ;                   5: .X....
    ;                   6: XXXXX.
    ;                   7: ......
    ; -----------------------------------------------------------------------
    .db 0b0111001000100000   ; r0:.XXX.. r1:X...X.
    .db 0b0000100001000000   ; r2:....X. r3:...X..
    .db 0b0010000100000000   ; r4:..X... r5:.X....
    .db 0b1111100000000000   ; r6:XXXXX. r7:......

    ; -----------------------------------------------------------------------
    ; Merkki 3: '3'       sarake: 012345
    ;                   0: .XXX..
    ;                   1: X...X.
    ;                   2: ....X.
    ;                   3: ..XX..
    ;                   4: ....X.
    ;                   5: X...X.
    ;                   6: .XXX..
    ;                   7: ......
    ; -----------------------------------------------------------------------
    .db 0b0111001000100000   ; r0:.XXX.. r1:X...X.
    .db 0b0000100011000000   ; r2:....X. r3:..XX..
    .db 0b0000101000100000   ; r4:....X. r5:X...X.
    .db 0b0111000000000000   ; r6:.XXX.. r7:......

    ; -----------------------------------------------------------------------
    ; Merkki 4: '4'       sarake: 012345
    ;                   0: ...X..
    ;                   1: ..XX..
    ;                   2: .X.X..
    ;                   3: X..X..
    ;                   4: XXXXX.
    ;                   5: ...X..
    ;                   6: ...X..
    ;                   7: ......
    ; -----------------------------------------------------------------------
    .db 0b0001000011000000   ; r0:...X.. r1:..XX..
    .db 0b0101001001000000   ; r2:.X.X.. r3:X..X..
    .db 0b1111100001000000   ; r4:XXXXX. r5:...X..
    .db 0b0001000000000000   ; r6:...X.. r7:......

    ; -----------------------------------------------------------------------
    ; Merkki 5: '5'       sarake: 012345
    ;                   0: XXXXX.
    ;                   1: X.....
    ;                   2: XXXX..
    ;                   3: ....X.
    ;                   4: ....X.
    ;                   5: X...X.
    ;                   6: .XXX..
    ;                   7: ......
    ; -----------------------------------------------------------------------
    .db 0b1111101000000000   ; r0:XXXXX. r1:X.....
    .db 0b1111000000100000   ; r2:XXXX.. r3:....X.
    .db 0b0000101000100000   ; r4:....X. r5:X...X.
    .db 0b0111000000000000   ; r6:.XXX.. r7:......

    ; -----------------------------------------------------------------------
    ; Merkki 6: '6'       sarake: 012345
    ;                   0: .XXX..
    ;                   1: X.....
    ;                   2: X.....
    ;                   3: XXXX..
    ;                   4: X...X.
    ;                   5: X...X.
    ;                   6: .XXX..
    ;                   7: ......
    ; -----------------------------------------------------------------------
    .db 0b0111001000000000   ; r0:.XXX.. r1:X.....
    .db 0b1000001111000000   ; r2:X..... r3:XXXX..
    .db 0b1000101000100000   ; r4:X...X. r5:X...X.
    .db 0b0111000000000000   ; r6:.XXX.. r7:......

    ; -----------------------------------------------------------------------
    ; Merkki 7: '7'       sarake: 012345
    ;                   0: XXXXX.
    ;                   1: ....X.
    ;                   2: ...X..
    ;                   3: ...X..
    ;                   4: ..X...
    ;                   5: ..X...
    ;                   6: ..X...
    ;                   7: ......
    ; -----------------------------------------------------------------------
    .db 0b1111100000100000   ; r0:XXXXX. r1:....X.
    .db 0b0001000001000000   ; r2:...X.. r3:...X..
    .db 0b0010000010000000   ; r4:..X... r5:..X...
    .db 0b0010000000000000   ; r6:..X... r7:......

    ; -----------------------------------------------------------------------
    ; Merkki 8: '8'       sarake: 012345
    ;                   0: .XXX..
    ;                   1: X...X.
    ;                   2: X...X.
    ;                   3: .XXX..
    ;                   4: X...X.
    ;                   5: X...X.
    ;                   6: .XXX..
    ;                   7: ......
    ; -----------------------------------------------------------------------
    .db 0b0111001000100000   ; r0:.XXX.. r1:X...X.
    .db 0b1000100111000000   ; r2:X...X. r3:.XXX..
    .db 0b1000101000100000   ; r4:X...X. r5:X...X.
    .db 0b0111000000000000   ; r6:.XXX.. r7:......

    ; -----------------------------------------------------------------------
    ; Merkki 9: '9'       sarake: 012345
    ;                   0: .XXX..
    ;                   1: X...X.
    ;                   2: X...X.
    ;                   3: .XXXX.
    ;                   4: ....X.
    ;                   5: ....X.
    ;                   6: .XXX..
    ;                   7: ......
    ; -----------------------------------------------------------------------
    .db 0b0111001000100000   ; r0:.XXX.. r1:X...X.
    .db 0b1000100111100000   ; r2:X...X. r3:.XXXX.
    .db 0b0000100000100000   ; r4:....X. r5:....X.
    .db 0b0111000000000000   ; r6:.XXX.. r7:......

    ; -----------------------------------------------------------------------
    ; Merkki 10: ':'      sarake: 012345
    ;                   0: ......
    ;                   1: ..X...
    ;                   2: ..X...
    ;                   3: ......
    ;                   4: ..X...
    ;                   5: ..X...
    ;                   6: ......
    ;                   7: ......
    ; -----------------------------------------------------------------------
    .db 0b0000000010000000   ; r0:...... r1:..X...
    .db 0b0010000000000000   ; r2:..X... r3:......
    .db 0b0010000010000000   ; r4:..X... r5:..X...
    .db 0b0000000000000000   ; r6:...... r7:......

    ; -----------------------------------------------------------------------
    ; Merkki 11: '.'      sarake: 012345
    ;                   0: ......
    ;                   1: ......
    ;                   2: ......
    ;                   3: ......
    ;                   4: ......
    ;                   5: ..XX..
    ;                   6: ..XX..
    ;                   7: ......
    ; -----------------------------------------------------------------------
    .db 0b0000000000000000   ; r0:...... r1:......
    .db 0b0000000000000000   ; r2:...... r3:......
    .db 0b0000000011000000   ; r4:...... r5:..XX..
    .db 0b0011000000000000   ; r6:..XX.. r7:......

    ; -----------------------------------------------------------------------
    ; Merkki 12: ' '      (välilyönti — kaikki tyhjää)
    ; -----------------------------------------------------------------------
    .db 0b0000000000000000   ; r0:...... r1:......
    .db 0b0000000000000000   ; r2:...... r3:......
    .db 0b0000000000000000   ; r4:...... r5:......
    .db 0b0000000000000000   ; r6:...... r7:......

